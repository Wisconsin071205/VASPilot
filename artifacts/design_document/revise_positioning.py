def revise(filename, changes):
    path = ROOT / filename
    source = path.read_text(encoding='utf-8')
    tree = ast.parse(source)
    substitutions = {}
    for node in ast.walk(tree):
        if not isinstance(node, ast.Constant) or not isinstance(node.value, str):
            continue
        value = node.value
        if value in COMMON:
            substitutions[ast.get_source_segment(source, node)] = repr(COMMON[value])
            continue
        for prefix, replacement in changes.items():
            if value.startswith(prefix):
                substitutions[ast.get_source_segment(source, node)] = repr(replacement)
                break
    for old,new in substitutions.items():
        source=source.replace(old,new)
    source=source.replace("'competition_submission'", "'competition_submission'/'修订版'")
    source=source.replace('rsci_作品简介.docx','远端控制智能体_作品简介.docx').replace('rsci_设计文档.docx','远端控制智能体_作品设计文档.docx')
    if filename=='build_intro.py':
        source=source.replace('doc.save(OUT)', 'OUT.parent.mkdir(parents=True, exist_ok=True)\ndoc.save(OUT)')
    else:
        source=source.replace("'模型服务'", "'模型服务  仅本机访问'")
        source=source.replace("'SSH 传输与 Gateway'", "'多服务器连接与路由  SSH 与 Gateway'")
        source=source.replace("'默认经 Vlab 中转，或从本机直连目标 HPC'", "'本机 → Vlab 中转 → 多台服务器，或本机分别 SSH 直连'")
        source=source.replace("'HPC 计算与材料生态'", "'多台计算服务器  无需访问模型 API'")
    path.write_text(source,encoding='utf-8')
    print(filename, len(substitutions), 'revisions')


